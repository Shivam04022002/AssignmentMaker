// Shared pen habits of this hand.
/** Upstroke from the baseline into a letter starting at (x, y). */
const entry = (x, y) => s().M(0, 0.06).Q(x * 0.6, y * 0.45, x, y);
/** A tall looped ascender from the baseline: up, round the top, down. */
const loopUp = (x, top = 1.72) =>
  s()
    .M(0, 0.06)
    .Q(x + 0.12, top * 0.42, x + 0.12, top * 0.82)
    .Q(x + 0.13, top, x + 0.02, top - 0.02)
    .Q(x - 0.07, top - 0.06, x - 0.02, top * 0.62)
    .L(x, 0);
/** Exit: down to the baseline, then a short rise to the right. */
const exitFrom = (st, x, w) => st.L(x, 0.12).Q(x + 0.02, 0, x + 0.12, 0.04).Q(w - 0.06, 0.08, w, 0.18);

