/**
 * Lang2 glyph set — the joined school hand of the Lang2 reference
 * (reference/Lang2.png), traced from enlarged crops of the page.
 *
 * Same units and builder as Lang1 (x-height 1, baseline 0, y up), but the
 * hand is different:
 *   - most small letters begin with an upstroke from the baseline (an
 *     entry) and end with a short rise to the right (an exit), so letters
 *     in a word touch and flow — semi-cursive, not every pair joins
 *   - o, v, w leave from the top (the next letter is joined at x-height)
 *   - b, h, k, l have tall looped ascenders; f has a top hook and a loop
 *     below the line; g, j, y have long J-like descenders
 *   - r is the cursive r (up, a small flag, down); s is the cursive s
 *     (pointed top, closed base); e is looped
 *   - I and T have wavy top bars; W, M, C are rounded
 *   - small x-height, long ascenders (≈1.75) and descenders (≈1.0)
 *
 * The set is complete: capitals, digits, punctuation and symbols are all
 * Lang2's own (no Lang1 fallback). Characters it cannot write get the
 * neutral fallback mark.
 */
